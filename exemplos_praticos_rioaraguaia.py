"""## 5. Caça ao fogo 🔥

No dia 8 de agosto de 2021 ocorreu um enorme incêndio em Eubeia, ilha localizada na Grécia.

Através da imagem obtida no dia conseguimos mostrar duas coisas legais:

1. **Ver através da fumaça** — a composição falsa-cor SWIR (B12, B8A, B04) enxerga através da fumaça,
   mostra o **fogo ativo** em laranja/vermelho e a **cicatriz de queimada** em marrom escuro.
2. **Medir a área queimada** — o índice NBR = (B08 − B12)/(B08 + B12) cai muito depois do fogo.
   A diferença antes − depois (**dNBR**) dá a severidade (classes do USGS).

> As datas antes/depois são um ponto de partida: ajuste conforme a data do fogo que vocês encontrarem.
"""

EVAL_FOGO = """
//VERSION=3
function setup() {
  return {
    input: [{ bands: ["B02", "B03", "B04", "B08", "B8A", "B12", "SCL", "dataMask"] }],
    output: { bands: 8, sampleType: "FLOAT32" }
  };
}
function evaluatePixel(s) {
  if (s.dataMask === 0) return [NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN];
  let nbr  = (s.B08 - s.B12) / (s.B08 + s.B12);
  let ndwi = (s.B03 - s.B08) / (s.B03 + s.B08);
  let nuvem = [3, 8, 9, 10].includes(s.SCL) ? 1 : 0;
  // 0-2: RGB | 3-5: falsa-cor SWIR | 6: NBR | 7: NDWI (nuvem vira NaN no NBR)
  return [s.B04, s.B03, s.B02, s.B12, s.B8A, s.B04, nuvem ? NaN : nbr, ndwi];
}
"""

# Parte 1: a mesma cena, "olhos humanos" vs "olhos SWIR"
BBOXfogo = (22.95, 38.70, 23.55, 39.05)

fogo = baixar(EVAL_FOGO, BBOXfogo, "2021-08-08", "2021-08-08", res_m=30, max_nuvem=100)

fig, axes = plt.subplots(1, 2, figsize=(20, 10))
axes[0].imshow(realce(fogo[..., 0:3]));      axes[0].set_title("Cor verdadeira: só fumaça", fontsize=14)
axes[1].imshow(realce(fogo[..., 3:6], 2.0)); axes[1].set_title("Falsa-cor SWIR (B12, B8A, B04): fogo e cicatriz", fontsize=14)
for ax in axes: ax.axis("off")
plt.tight_layout(); plt.show()

# Parte 2: área queimada com dNBR
antes  = baixar(EVAL_FOGO, BBOXfogo, "2021-07-15", "2021-07-31", res_m=30)
depois = baixar(EVAL_FOGO, BBOXfogo, "2021-08-20", "2021-09-10", res_m=30)

dnbr = antes[..., 6] - depois[..., 6]
# Água que secou também muda o NBR -> descartamos pixels que eram água em qualquer data
dnbr[(antes[..., 7] > 0) | (depois[..., 7] > 0)] = np.nan

limites_dnbr = [-np.inf, 0.10, 0.27, 0.44, 0.66, np.inf]                     # classes USGS
nomes_fogo   = ["Não queimado", "Baixa", "Moderada-baixa", "Moderada-alta", "Alta"]
cores_fogo   = ["#e5f5e0", "#fee391", "#fe9929", "#d7301f", "#67000d"]
classe  = np.digitize(dnbr, limites_dnbr[1:-1]).astype(float)
classe[np.isnan(dnbr)] = np.nan

px_ha = area_pixel_km2(BBOXfogo, dnbr) * 100
queimado_ha = np.nansum(dnbr > 0.10) * px_ha

fig, axes = plt.subplots(1, 3, figsize=(27, 9))
axes[0].imshow(realce(antes[..., 3:6], 2.0));  axes[0].set_title("Antes (jul) — SWIR")
axes[1].imshow(realce(depois[..., 3:6], 2.0)); axes[1].set_title("Depois (ago–set) — SWIR")
axes[2].imshow(classe, cmap=mcolors.ListedColormap(cores_fogo), vmin=-0.5, vmax=4.5, interpolation="nearest")
axes[2].set_title(f"Severidade (dNBR) — {queimado_ha:,.0f} ha queimados".replace(",", "."))
axes[2].legend(handles=[plt.Rectangle((0, 0), 1, 1, color=c) for c in cores_fogo],
               labels=[f"{n}: {np.nansum(classe == i) * px_ha:,.0f} ha".replace(",", ".") for i, n in enumerate(nomes_fogo)],
               loc="lower right")
for ax in axes: ax.axis("off")
plt.tight_layout(); plt.show()
print(f"≈ {queimado_ha/100:.1f} km² ≈ {queimado_ha/0.714:,.0f} campos de futebol".replace(",", "."))

"""## 6. O computador descobre as classes sozinho (K-means)

Sem dizer ao algoritmo o que é água, mata ou areia: ele agrupa pixels com "assinatura espectral" parecida.
Depois a classificação de cada grupo é determinado **manualmente** olhando o mapa — é exatamente o fluxo de uma classificação não supervisionada.
"""

from sklearn.cluster import KMeans

EVAL_BANDAS = """
//VERSION=3
function setup() {
  return {
    input: [{ bands: ["B02", "B03", "B04", "B08", "B11", "B12", "dataMask"] }],
    output: { bands: 6, sampleType: "FLOAT32" }
  };
}
function evaluatePixel(s) {
  if (s.dataMask === 0) return [NaN, NaN, NaN, NaN, NaN, NaN];
  return [s.B02, s.B03, s.B04, s.B08, s.B11, s.B12];
}
"""
bandas = baixar(EVAL_BANDAS, BBOX, "2024-07-01", "2024-08-31")
B02, B03, B04, B08, B11, B12 = np.moveaxis(bandas, -1, 0)
ndvi = (B08 - B04) / (B08 + B04)
ndwi = (B03 - B08) / (B03 + B08)

X = np.stack([B02, B03, B04, B08, B11, B12, ndvi, ndwi], axis=-1).reshape(-1, 8)
validos = ~np.isnan(X).any(axis=1)

K = 6   # troque e veja o que acontece!
idx_validos = np.flatnonzero(validos)
amostra = np.random.default_rng(0).choice(idx_validos, min(50_000, idx_validos.size), replace=False)
modelo = KMeans(n_clusters=K, n_init=10, random_state=0).fit(X[amostra])

rotulos = np.full(X.shape[0], -1)
rotulos[validos] = modelo.predict(X[validos])
mapa_kmeans = np.ma.masked_less(rotulos.reshape(B02.shape), 0)

fig, axes = plt.subplots(1, 2, figsize=(20, 10))
axes[0].imshow(realce(np.dstack([B04, B03, B02]))); axes[0].set_title("RGB")
im = axes[1].imshow(mapa_kmeans, cmap="tab10", vmin=-0.5, vmax=9.5, interpolation="nearest")
axes[1].set_title(f"K-means com {K} grupos")
for ax in axes: ax.axis("off")
fig.colorbar(im, ax=axes[1], ticks=range(K), fraction=0.04)
plt.tight_layout(); plt.show()

for k in range(K):
    centro = modelo.cluster_centers_[k]
    print(f"grupo {k}: {np.mean(mapa_kmeans == k)*100:5.1f}% da área | NDVI médio {centro[6]:+.2f} | NDWI médio {centro[7]:+.2f}")

