"""## 1.4 `AUTO` × `FLOAT32`: imagem para VER ou dado para CALCULAR?

* **`AUTO`** converte o intervalo 0–1 para 0–255 (inteiro). Ótimo para visualizar, mas **tudo abaixo de 0 vira 0**
  e tudo acima de 1 vira 255.
* **`FLOAT32`** devolve o número de verdade, com casas decimais e sinal.

Índices como NDWI e NDVI vão de **−1 a +1** — com `AUTO` metade da informação se perde.
"""

def ndwi_script(sample_type):
    return f"""
//VERSION=3
function setup() {{
  return {{
    input: ["B03", "B08"],
    output: {{ bands: 1, sampleType: "{sample_type}" }} }};
}}
function evaluatePixel(sample) {{
  return [(sample.B03 - sample.B08) / (sample.B03 + sample.B08)];
}}
"""

ndwi_auto = pedir(ndwi_script("AUTO"))
ndwi_float = pedir(ndwi_script("FLOAT32"))

for nome, arr in [("AUTO", ndwi_auto), ("FLOAT32", ndwi_float)]:
    print(f"{nome:8s} dtype={str(arr.dtype):8s} min={np.nanmin(arr):8.3f}  max={np.nanmax(arr):8.3f}  "
          f"pixels = 0: {np.mean(arr == 0)*100:4.1f}%")

fig, axes = plt.subplots(1, 3, figsize=(24, 7))
axes[0].imshow(ndwi_auto, cmap="gray");  axes[0].set_title("NDWI com AUTO (0–255, negativos viraram 0)")
im = axes[1].imshow(ndwi_float, cmap="RdBu", vmin=-1, vmax=1); axes[1].set_title("NDWI com FLOAT32 (−1 a +1)")
fig.colorbar(im, ax=axes[1], fraction=0.046)
for ax in axes[:2]: ax.axis("off")
axes[2].hist(ndwi_float[np.isfinite(ndwi_float)].ravel(), bins=100, color="#4292c6")
