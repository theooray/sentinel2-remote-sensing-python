"""## 1.6 ONDE e em que TAMANHO: coordenadas e resolução

**Como pegar as coordenadas:** defina um retângulo no [Bounding Box Tool](https://boundingbox.klokantech.com/) (**Copie as coordenadas em formato CSV**)
ou em [bbox finder](http://bboxfinder.com) e copie os limites. ⚠️ <font color="orange">A API usa **longitude primeiro** (o Google Maps mostra latitude primeiro).</font>⚠️

Em vez de `bbox` também dá para mandar um **polígono** GeoJSON — útil para recortar
exatamente uma fazenda, município ou lago.

**Resolução:** `width`/`height` definem quantos pixels a imagem tem, e portanto quantos metros cada pixel representa.
O Sentinel-2 tem no máximo 10 m; pedir mais pixels que isso não cria detalhe novo, só aumenta o arquivo.
"""

lon_min, lat_min, lon_max, lat_max = requisicao["input"]["bounds"]["bbox"]

#============================| Conversão coordenas -> km |==============================
#longitude = 111,32·cos(lat) (meridianos convergem nos polos)
#latitude ≈ 110,574 (quase constante)
largura_km = (lon_max - lon_min) * 111.32 * np.cos(np.radians((lat_min + lat_max) / 2))
altura_km = (lat_max - lat_min) * 110.574
#=======================================================================================

w, h = requisicao["output"]["width"], requisicao["output"]["height"]

print(f"Área: {largura_km:.1f} km × {altura_km:.1f} km")
print(f"Pedimos {w} × {h} px  →  cada pixel ≈ {largura_km*1000/w:.0f} m × {altura_km*1000/h:.0f} m")
print(f"Para ter 10 m/pixel precisaríamos de {largura_km*100:.0f} × {altura_km*100:.0f} px")
# Repare: largura e altura em km são diferentes, mas pedimos 512 × 512 → a imagem sai levemente esticada.

"""## 1.7 Juntando tudo: a função `baixar()`

Tudo o que vimos — montar o JSON, renovar o token, escolher a cena com menos nuvem, calcular `width`/`height`
a partir da resolução em metros (sem esticar a imagem) e abrir o TIFF — fica guardado numa função só.
Nos exemplos basta dizer **qual receita, onde e quando**.
"""

def tamanho_px(bbox, res_m):
    #Largura/altura em pixels mantendo a proporção real da área (evita imagem esticada).

    # res_m é o parametro que defini a quantidade de metros por pixel que a imagem vai retornar
    # res_m = 10 -> cada pixel terá 10m na imagem (pros: mais preciso os dados, contra: imagem mais pesada)
    # res_m = 60 -> cada pixel terá 60m na imagem (pros: mais leve e economico, contra: menos detalhes)

    lon_min, lat_min, lon_max, lat_max = bbox

    lat_c = np.radians((lat_min + lat_max) / 2)
    largura_m = (lon_max - lon_min) * 111_320 * np.cos(lat_c)
    altura_m = (lat_max - lat_min) * 110_574

    return int(round(largura_m / res_m)), int(round(altura_m / res_m))

def area_pixel_km2(bbox, img):
    #Área aproximada de 1 pixel em km² (para transformar contagem de pixels em área).

    lon_min, lat_min, lon_max, lat_max = bbox

    lat_c = np.radians((lat_min + lat_max) / 2)
    largura_km = (lon_max - lon_min) * 111.32 * np.cos(lat_c)
    altura_km = (lat_max - lat_min) * 110.574

    return largura_km * altura_km / (img.shape[0] * img.shape[1])

def baixar(evalscript, bbox, inicio, fim, res_m=20, max_nuvem=30, ordem="leastCC"):
    #==========================================================================================
    #Baixa um mosaico Sentinel-2 L2A. Datas no formato 'AAAA-MM-DD'.
    #ordem='leastCC' pega a cena com MENOS nuvem do período (o padrão da API é a mais recente).
    #==========================================================================================

    garantir_token()
    largura, altura = tamanho_px(bbox, res_m)
    request = {
        "input": {
            "bounds": {"bbox": list(bbox),
                       "properties": {"crs": "http://www.opengis.net/def/crs/OGC/1.3/CRS84"}},
            "data": [{
                "type": "sentinel-2-l2a",
                "dataFilter": {
                    "timeRange": {"from": f"{inicio}T00:00:00Z", "to": f"{fim}T23:59:59Z"},
                    "maxCloudCoverage": max_nuvem,
                    "mosaickingOrder": ordem,
                },
            }],
        },
        "output": {"width": largura, "height": altura},
        "evalscript": evalscript,
    }
    r = oauth.post(PROCESS_URL, json=request, headers={"Accept": "image/tiff"})
    if r.status_code != 200:
        raise RuntimeError(f"Erro {r.status_code}: {r.text[:300]}")
    return tifffile.imread(io.BytesIO(r.content))

def realce(rgb, ganho=2.5):
    """Refletância (0–1) -> imagem exibível."""
    return np.clip(np.nan_to_num(rgb) * ganho, 0, 1)

