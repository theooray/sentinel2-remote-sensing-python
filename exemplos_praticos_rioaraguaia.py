#================================================================================================================================================================================
# ÁREA VARIAVEL — para trocar de rio, mude só >>BBOX e PERIODOS<<.

# Ordem: (lon_min, lat_min, lon_max, lat_max)  ← LONGITUDE PRIMEIRO! (o Google Maps mostra lat, lon) -> recomendação, copie em formato CSV: https://boundingbox.klokantech.com/

# Tamanho máximo: ~50 km de lado com res_m=20 (limite de 2500 px da API); para áreas maiores aumente res_m na função baixar().

# PERIODOS: o 1º deve ser a CHEIA e o último a SECA do rio escolhido (o PERIODO muda de rio para rio).
#================================================================================================================================================================================

BBOX = (-50.2990096611, -9.8973521206, -50.1053756279, -9.6984229431)

PERIODOS = {
    "Cheia (abr–mai)":         ("2024-04-01", "2024-05-31"),
    "Intermediário (jun)":     ("2024-06-01", "2024-06-30"),
    "Seca (jul–ago)":          ("2024-07-01", "2024-08-31"),
}

#===================================================================================
# Um único evalscript devolve TUDO que os exemplos 1–4 precisam:
# bandas 0–2 = RGB, 3 = NDWI, 4 = máscara de nuvem (a partir da banda SCL do L2A)
#===================================================================================

EVAL_AGUA = """
//VERSION=3
function setup() {
  return {
    input: [{ bands: ["B02", "B03", "B04", "B08", "SCL", "dataMask"] }],
    output: { bands: 5, sampleType: "FLOAT32" }
  };
}
function evaluatePixel(s) {
  if (s.dataMask === 0) return [NaN, NaN, NaN, NaN, NaN];
  let ndwi = (s.B03 - s.B08) / (s.B03 + s.B08);
  // SCL: 3 = sombra de nuvem, 8/9 = nuvem, 10 = cirrus
  let nuvem = [3, 8, 9, 10].includes(s.SCL) ? 1 : 0;
  return [s.B04, s.B03, s.B02, ndwi, nuvem];
}
"""

"""## 1. Quanto de água o rio perdeu?

Em vez de só *olhar* o NDWI, vamos **medir**: pixel com NDWI > 0 e sem nuvem = água.
Contando os pixels e multiplicando pela área de cada um, temos km².
"""

cenas = {}
area_agua = {}
for nome, (ini, fim) in PERIODOS.items():
    img = baixar(EVAL_AGUA, BBOX, ini, fim)
    cenas[nome] = img
    ndwi, nuvem = img[..., 3], img[..., 4] == 1
    agua = (ndwi > 0) & ~nuvem
    area_agua[nome] = agua.sum() * area_pixel_km2(BBOX, img)
    print(f"{nome:26s} água = {area_agua[nome]:6.1f} km²   nuvem = {nuvem.mean()*100:4.1f}%")

fig, axes = plt.subplots(1, 4, figsize=(24, 6), gridspec_kw={"width_ratios": [1, 1, 1, 1.2]})
for ax, (nome, img) in zip(axes, cenas.items()):
    ax.imshow(realce(img[..., :3]))
    ax.imshow(np.ma.masked_where(~(img[..., 3] > 0), img[..., 3]), cmap="Blues", vmin=-0.2, vmax=0.6, alpha=0.8)
    ax.set_title(f"{nome}\n{area_agua[nome]:.1f} km² de água", fontsize=13)
    ax.axis("off")

axes[3].bar(area_agua.keys(), area_agua.values(), color=["#08519c", "#4292c6", "#c6dbef"])
axes[3].set_ylabel("Área de água (km²)")
axes[3].tick_params(axis="x", rotation=20)
cheia, seca = list(area_agua.values())[0], list(area_agua.values())[-1]   # 1º período = cheia, último = seca
axes[3].set_title(f"O rio encolheu {100*(cheia-seca)/cheia:.0f}% da cheia para a seca")
plt.tight_layout(); plt.show()

