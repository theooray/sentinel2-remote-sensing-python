"""## 3. Mapa de mudança: cheia × seca

Combinando as duas máscaras de água em uma só imagem com 4 classes (álgebra de mapas):

* **Água permanente** — é água nas duas épocas (o canal principal)
* **Só na cheia** — planície de inundação / bancos de areia que emergem na seca
* **Só na seca** — geralmente ruído, sombra ou lagoas isoladas
* **Terra**
"""

c, s = list(cenas.values())[0], list(cenas.values())[-1]   # 1º período = cheia, último = seca
agua_c = (c[..., 3] > 0) & (c[..., 4] != 1)
agua_s = (s[..., 3] > 0) & (s[..., 4] != 1)
nuvem_qualquer = (c[..., 4] == 1) | (s[..., 4] == 1)

classes = np.zeros(agua_c.shape, dtype=np.uint8)      # 0 = terra
classes[agua_c & agua_s] = 1                           # permanente
classes[agua_c & ~agua_s] = 2                          # só na cheia
classes[~agua_c & agua_s] = 3                          # só na seca
classes[nuvem_qualquer] = 4                            # sem dado (nuvem)

nomes = ["Terra", "Água permanente", "Só na cheia", "Só na seca", "Nuvem"]
cores = ["#f0ead6", "#08306b", "#6baed6", "#e6550d", "#bdbdbd"]
px = area_pixel_km2(BBOX, c)

fig, ax = plt.subplots(figsize=(10, 10))
ax.imshow(classes, cmap=mcolors.ListedColormap(cores), vmin=-0.5, vmax=4.5, interpolation="nearest")
ax.legend(handles=[plt.Rectangle((0, 0), 1, 1, color=cor) for cor in cores],
          labels=[f"{n}: {(classes == i).sum() * px:.1f} km²" for i, n in enumerate(nomes)],
          loc="lower right", fontsize=11)
ax.set_title("Mudança da lâmina d'água — Rio Araguaia 2024", fontsize=14); ax.axis("off")
plt.show()

"""### 3b. O mesmo mapa, interativo

Cada classe vira uma **camada separada** sobre uma imagem de satélite de fundo. No painel do canto superior direito
dá para ligar/desligar cada uma (ex.: deixar só "Só na cheia" para ver a planície de inundação),
e também as fotos RGB da cheia e da seca para comparar. Dá zoom, tela cheia e o mapa é salvo como HTML.
"""

import folium
from folium.plugins import Fullscreen, GroupedLayerControl
from folium.map import CustomPane

def mascara_rgba(mask, cor_hex, alpha=200):
    """Máscara booleana -> imagem RGBA: cor onde é True, transparente no resto."""
    r, g, b = mcolors.to_rgb(cor_hex)
    rgba = np.zeros((*mask.shape, 4), dtype=np.uint8)
    rgba[mask] = [int(r*255), int(g*255), int(b*255), alpha]
    return rgba

def rgb_rgba(img):
    """Cena Sentinel-2 -> RGBA para sobrepor no mapa (sem dado = transparente)."""
    rgba = np.zeros((*img.shape[:2], 4), dtype=np.uint8)
    rgba[..., :3] = (realce(img[..., :3]) * 255).astype(np.uint8)
    rgba[..., 3] = np.where(np.isnan(img[..., 0]), 0, 255)
    return rgba

lon_min, lat_min, lon_max, lat_max = BBOX
limites = [[lat_min, lon_min], [lat_max, lon_max]]
nomes_periodos = list(cenas)

# ==== AJUSTES DE TAMANHO ====
LARGURA, ALTURA = 1300, 650   # tamanho do mapa na TELA do notebook, em pixels
REDUZIR = 2                   # reduz o tamanho do arquivo
r = slice(None, None, REDUZIR)
#=============================

figura = folium.Figure(width=LARGURA, height=ALTURA)
mapa = folium.Map(location=[(lat_min + lat_max) / 2, (lon_min + lon_max) / 2], zoom_start=12, tiles=None).add_to(figura)
CustomPane("fotos", z_index=350).add_to(mapa)
folium.TileLayer("https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}",
                 attr="Esri World Imagery", name="Satélite (fundo)").add_to(mapa)

folium.TileLayer("https://server.arcgisonline.com/ArcGIS/rest/services/World_Street_Map/MapServer/tile/{z}/{y}/{x}",
                 attr="Esri World Street Map", name="Ruas (fundo)").add_to(mapa)

# Fotos Sentinel-2 (começam escondidas)
fotos = []
for nome, cena in [("Nenhuma", None), (f"📷 RGB {nomes_periodos[0]}", c), (f"📷 RGB {nomes_periodos[-1]}", s)]:
    grupo = folium.FeatureGroup(name=nome, control=False, show=(cena is None))
    if cena is not None:
        folium.raster_layers.ImageOverlay(rgb_rgba(cena[r, r]), bounds=limites, pane="fotos").add_to(grupo)
    grupo.add_to(mapa)
    fotos.append(grupo)

# Uma camada por classe; o nome já funciona como legenda (cor + área)
for i in [1, 2, 3, 4]:                                  # 0 = terra fica transparente
    km2 = (classes == i).sum() * px
    rotulo = f'<span style="color:{cores[i]}; font-size:18px">■</span> {nomes[i]} ({km2:.1f} km²)'
    folium.raster_layers.ImageOverlay(mascara_rgba((classes == i)[r, r], cores[i]), bounds=limites,
                                      name=rotulo, show=(i != 4)).add_to(mapa)

folium.LayerControl(collapsed=False).add_to(mapa)
GroupedLayerControl(groups={"Imagem Sentinel-2": fotos}, exclusive_groups=True, collapsed=False).add_to(mapa)
Fullscreen().add_to(mapa)
mapa.save("mapa_mudanca_cheia_seca.html")
print(f"Arquivo: {os.path.getsize('mapa_mudanca_cheia_seca.html') / 1e6:.1f} MB")
figura

